"""Render the approved boot selector artwork as column-oriented indexed runs."""
import argparse
from datetime import datetime
from pathlib import Path
import sys
from zoneinfo import ZoneInfo

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "pydeps"))
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parents[1]
INK = "#151717"
MUTED = "#444947"
PAPER = "#eeeee7"
SIGNAL = "#fffa00"
FONT_DIR = Path("C:/Windows/Fonts")
ROWS = [
    ("01", "Android", "Android 10 GSI", "4.4.23+"),
    ("02", "Linux", "Debian 13  /  GNOME", "7.3.1"),
    ("03", "Reboot", "Restart the tablet", ""),
    ("04", "Power Off", "Turn off the tablet", ""),
]


def font(size, mono=False, weight=None):
    result = ImageFont.truetype(str(FONT_DIR / ("consola.ttf" if mono else "bahnschrift.ttf")), size)
    if weight:
        result.set_variation_by_axes([weight, 90])
    return result


def text(draw, xy, value, size, *, color=INK, mono=False, weight=None, anchor="lt"):
    draw.text(xy, value, font=font(size, mono, weight), fill=color, anchor=anchor)


def row(index, selected):
    number, title, subtitle, version = ROWS[index]
    image = Image.new("RGB", (1051, 105), PAPER)
    draw = ImageDraw.Draw(image)
    draw.polygon([(0, 0), (1025, 0), (1050, 25), (1050, 104), (0, 104)],
                 fill=SIGNAL if selected else "#e5e6df")
    if selected:
        draw.rectangle((0, 0, 7, 104), fill=INK)
    text(draw, (44, 27), number, 32, mono=True)
    draw.line((118, 24, 118, 79), fill="#85877e")
    text(draw, (150, 12), title, 49, weight=700)
    text(draw, (152, 70), subtitle, 21, color=MUTED, weight=450)
    text(draw, (937, 39), version, 28, mono=True, anchor="rt")
    if selected:
        draw.line((971, 52, 1009, 52), fill=INK, width=3)
        draw.line([(997, 41), (1009, 52), (997, 63)], fill=INK, width=3)
    return image


def detail(concept, choice):
    image = concept.crop((1204, 815, 1849, 1016))
    if choice == 1:
        return image
    draw = ImageDraw.Draw(image)
    draw.rectangle((0, 36, 644, 200), fill=PAPER)
    if choice == 0:
        text(draw, (0, 51), "Linux 4.4.23+", 53, weight=700)
        text(draw, (643, 68), "ARM64 / #1", 23, mono=True, anchor="rt")
        text(draw, (3, 120), "Toolchain", 21, color=MUTED, weight=500)
        text(draw, (643, 120), "GCC 4.9.x", 24, weight=500, anchor="rt")
        draw.line((3, 154, 643, 154), fill="#a3a6a0")
        text(draw, (3, 167), "Kernel build", 21, color=MUTED, weight=500)
        text(draw, (643, 167), "2021-03-09 11:21 CST", 23, mono=True, anchor="rt")
    else:
        draw.rectangle((0, 0, 644, 35), fill=PAPER)
        text(draw, (3, 12), "//  POWER", 22, color=MUTED, mono=True)
        text(draw, (0, 51), ROWS[choice][1], 53, weight=700)
        text(draw, (3, 120), "Press Power to confirm", 23, color=MUTED, weight=500)
    return image


def encode(image, palette):
    indexed = image.quantize(palette=palette, dither=Image.Dither.NONE)
    pixels = indexed.load()
    width, height = indexed.size
    data = bytearray()
    for x in range(width):
        y = height - 1
        while y >= 0:
            color = pixels[x, y]
            length = 1
            while length < 256 and y >= length and pixels[x, y - length] == color:
                length += 1
            data.extend((length - 1, color))
            y -= length
    return data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", default="v0.1.121")
    parser.add_argument("--build-date", default=datetime.now(ZoneInfo("America/New_York")).strftime("%Y-%m-%d %H:%M %Z"))
    args = parser.parse_args()
    concept = Image.open(HERE / "docs" / "menu-concept.png").convert("RGB")
    assert concept.size == (1920, 1200)
    draw = ImageDraw.Draw(concept)
    draw.rectangle((1010, 1099, 1848, 1162), fill=PAPER)
    text(draw, (1847, 1117), f"SELECTOR {args.version}  /  {args.build_date}", 21, mono=True, anchor="rt")
    for index in range(4):
        concept.paste(row(index, index == 1), (73, 382 + 122 * index))
    regions = [("BASE", concept)]
    regions += [(f"ROW_{index}_{sel}", row(index, bool(sel))) for index in range(4) for sel in range(2)]
    regions += [(f"DETAIL_{index}", detail(concept, index)) for index in range(4)]
    # Build one palette from all visual states.
    swatches = Image.new("RGB", (1920, 1200 + 12 * 201), PAPER)
    swatches.paste(concept)
    for index, (_, image) in enumerate(regions[1:]):
        swatches.paste(image, (0, 1200 + index * 201))
    palette = swatches.quantize(colors=256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    raw_palette = palette.getpalette()
    code = ["/* Generated by make-art.py. */", "extern const u8 menu_art[];", "static const u32 menu_palette[256] = {"]
    for offset in range(0, 768, 24):
        code.append(" " + ", ".join("0xff%02x%02x%02x" % tuple(raw_palette[i:i+3])
                                    for i in range(offset, offset + 24, 3)) + ",")
    code.append("};")
    blob = bytearray()
    for name, image in regions:
        code.append(f"#define ART_{name} {len(blob)}")
        blob.extend(encode(image, palette))
    assert len(blob) < 1_000_000, len(blob)
    (HERE / "dualboot" / "menu-art.inc").write_text(
        "/* Generated by tools/make-menu-art.py. */\n" +
        "".join(" .byte " + ",".join(f"0x{x:02x}" for x in blob[i:i+24]) + "\n"
                for i in range(0, len(blob), 24)), encoding="ascii", newline="\n")
    (HERE / "dualboot" / "menu-art.h").write_text("\n".join(code) + "\n", encoding="ascii")
    concept.quantize(palette=palette, dither=Image.Dither.NONE).save(HERE / "docs" / "boot-menu.png")
    print(f"Packed selector artwork: {len(blob)} bytes")


if __name__ == "__main__":
    main()
